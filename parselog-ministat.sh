#!/bin/sh

# Проверяем, передан ли файл
if [ -z "$1" ]; then
	echo "Использование: $0 <путь_к_логу_h1load>" >&2
	exit 1
fi

# AWK парсит лог, убирает прогрев/конец и конвертирует суффиксы (k, M) в числа
awk '
    # Пропускаем комментарии
    /^#/ { next }

    # Работаем только со строками, где есть данные (больше 10 полей)
    # и игнорируем секцию перцентилей (в ней меньше полей)
    NF >= 12 {
        rps = $8

        # Нам нужны только боевые метрики. Если RPS равен "0.00", пропускаем строку
        if (rps == "0.00" || rps == "0") next

        # Конвертируем буквенные суффиксы в чистые числа
        if (rps ~ /k$/) { sub(/k$/, "", rps); rps = rps * 1000 }
        else if (rps ~ /M$/) { sub(/M$/, "", rps); rps = rps * 1000000 }

        # Сохраняем значения в массив
        lines[count++] = rps
    }

    END {
        # Отбрасываем первые 5 секунд (прогрев) и последние 5 секунд (спад/стоп)
        # Это даст ministat максимально чистые и стабильные данные
        warmup = 5
        cooldown = 5

        if (count <= (warmup + cooldown + 3)) {
            # Если лог слишком короткий, выводим всё что есть, кроме явных нулей
            for (i = 0; i < count; i++) print lines[i]
        } else {
            for (i = warmup; i < (count - cooldown); i++) {
                print lines[i]
            }
        }
    }
' "$1"
